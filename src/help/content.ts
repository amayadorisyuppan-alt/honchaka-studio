/** ヘルプ1枚ぶんの Markdown。**画面と同じものから作る** */
export function helpMarkdown(): string {
  const tabs = HELP_TABS.map(
    (t) =>
      `### ${t.title}\n\n${t.lead}\n\n` +
      t.can.map((c) => `- ${c}`).join('\n') +
      (t.notes?.length ? `\n\n**気をつけること**\n\n` + t.notes.map((n) => `- ${n}`).join('\n') : ''),
  ).join('\n\n');

  const bar =
    `### ${HELP_BAR.title}\n\n${HELP_BAR.lead}\n\n` +
    HELP_BAR.can.map((c) => `- ${c}`).join('\n') +
    `\n\n**気をつけること**\n\n` +
    HELP_BAR.notes.map((n) => `- ${n}`).join('\n');

  const d = HELP_EPUB_DIFF;
  const epubDiff =
    `${d.lead}\n\n` +
    `**${d.alwaysHead}**\n\n` +
    d.always.map((x) => `- ${x}`).join('\n') +
    `\n\n**${d.dependsHead}**\n\n` +
    d.depends.map((x) => `- ${x}`).join('\n') +
    `\n\n${d.check}`;

  const qa = HELP_QA.map((x) => `### ${x.q}\n\n${x.a}`).join('\n\n');

  const glossary = HELP_GLOSSARY.map((x) => `- **${x.term}**: ${x.def}`).join('\n');

  const r = HELP_REPAINT;
  const repaint =
    `${r.lead}\n\n` +
    `**${r.noHead}**\n\n` +
    r.no.map((x) => `- ${x}`).join('\n') +
    `\n\n**${r.yesHead}**\n\n` +
    r.yes.map((x) => `- ${x}`).join('\n') +
    `\n\n${r.note}`;

  const slow =
    `${HELP_SLOW.lead}\n\n${HELP_SLOW.check}\n\n` +
    HELP_SLOW.fix.map((x) => `- ${x}`).join('\n');

  return `# 「ひっちゃか本づくりスタジオ」の使い方

縦書き・横書きの日本語の本を、紙（PDF）と電子書籍（EPUB）で同時に作るソフトです。
本の入稿データを完成させるまでの**6つの工程**を画面の上に順番に並べていて、左から順に片づけていきます。
画面のいちばん下の**帯**は見た目の道具です。開いている工程に合わせて中身が変わります
（本文の見た目は本文の工程で、表紙の見た目は［表紙をつくる］で）。

このファイルは、**行き詰まったときに AI に読ませて聞く**こともできます。
「${HELP_QA[0].q}」のように、困っていることをそのまま聞いてください。

## 工程

${tabs}

## 用語集

${glossary}

## ${HELP_EPUB_DIFF.title}

${epubDiff}

## 画面下の帯

${bar}

## ${HELP_REPAINT.title}

${repaint}

## ${HELP_SLOW.title}

${slow}

## 困ったとき

${qa}
`;
}
