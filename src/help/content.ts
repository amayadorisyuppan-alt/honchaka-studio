import { EDITION } from '../edition';

/*
 * **版ごとの文の差し替え。**(2026-10-10)
 * ここに書く文は標準の版の文。版(src/edition)が差し替え(helpReplaces)と差し込み(helpInserts)を持っていれば、
 * 下の HELP_* を作るときに当てる(画面のパネルにも配る .md にも同じものが出る)。
 * 差し替えは「標準の版の文と1字も違わない文」だけに当たる。ここの文を直して当たらなくなった差し替えは
 * helpEditsUnused() に出る(版の検査がそれを見る)
 */
const usedEdits = new Set<string>();

function forEdition<T>(v: T): T {
  if (EDITION.helpReplaces.length === 0 && EDITION.helpInserts.length === 0) return v;
  return edit(v) as T;
}

function edit(v: unknown): unknown {
  if (typeof v === 'string') {
    const r = EDITION.helpReplaces.find((x) => x.from === v);
    if (!r) return v;
    usedEdits.add(r.from);
    return r.to;
  }
  if (Array.isArray(v)) {
    const out: unknown[] = [];
    for (const x of v) {
      out.push(edit(x));
      if (typeof x !== 'string') continue;
      for (const ins of EDITION.helpInserts) {
        if (ins.after !== x) continue;
        usedEdits.add(ins.after);
        out.push(ins.insert);
      }
    }
    return out;
  }
  if (v && typeof v === 'object') {
    const o: Record<string, unknown> = {};
    for (const [k, x] of Object.entries(v)) o[k] = edit(x);
    return o;
  }
  return v;
}

/** 版の差し替えのうち、どこにも当たらなかったもの(標準の版の文が変わって、差し替えが古くなった)。空なら全部当たった */
export function helpEditsUnused(): string[] {
  return [...EDITION.helpReplaces.map((x) => x.from), ...EDITION.helpInserts.map((x) => x.after)].filter(
    (s) => !usedEdits.has(s),
  );
}

