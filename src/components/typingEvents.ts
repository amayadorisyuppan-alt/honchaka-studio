// 手が止まってから店へ渡す欄(ColumnPageEditor の useLazyText)と、Ctrl+Z の受け口(App)の取り決め。
//
// **Ctrl+Z の前に、打ちかけの字を店へ渡しきる。**(2026-09-25 見直し S2-14)
// コラムの欄は打鍵を欄の中に溜め、手が止まって 0.4 秒たってから店へ渡す。その 0.4 秒のうちに
// Ctrl+Z を押すと、履歴のいちばん上はまだ「別の場所の直前の編集」(著者紹介の文・書名の書体など)で、
// App はそれを「この欄の打ち始め」と取り違えて戻していた(やり直しもできなかった)。
// App は Ctrl+Z を見たら、いま打っている欄へ FLUSH を送る。欄はその場で店へ渡し、渡したら
// COMMITTED を上へ流す。App はそれを見て「この欄の打ち始め」を記録し直してから判断する

/** 欄へ「いま渡して」と頼む(欄そのものに送る。上へは流さない) */
export const TYPING_FLUSH = 'studio:typing-flush';
/** 欄が「いま店へ渡した」と知らせる(上へ流す) */
export const TYPING_COMMITTED = 'studio:typing-committed';
/**
 * App が「この欄の打ち始めへ戻した」と欄に知らせる(欄そのものに送る)。
 * 欄はフォーカス中の外からの書き換えを受けない作りなので、これが無いと、データは戻ったのに
 * 欄には打った字が見えたまま残り、続けて打つと戻したはずの字がまた店へ入った(2026-09-26 検証で発見)
 */
export const TYPING_REVERTED = 'studio:typing-reverted';
