/** その工程のつぶやきを7割、共通を3割で1つ選ぶ。直前と同じものは避ける */
export function pickMurmur(step: StepId, last: string | null): string {
  const pool = Math.random() < 0.7 ? FROG_MURMURS[step] : FROG_MURMURS_ANY;
  const choices = pool.filter((s) => s !== last);
  return choices[Math.floor(Math.random() * choices.length)] ?? pool[0];
}
